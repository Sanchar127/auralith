def extract_chunk_ids_from_answer(
    answer: str,
) -> list[str]:
    """
    Extract explicit chunk citations from an answer.

    Supported examples:

        [chunk-123]
        (chunk-123)
        chunk-123

    Returns:
        Unique chunk IDs in the order they appear.
    """

    if not answer:
        return []

    pattern = (
        r"(?:\[|\()?"
        r"(chunk-[A-Za-z0-9_-]+)"
        r"(?:\]|\))?"
    )

    matches = re.findall(
        pattern,
        answer,
        flags=re.IGNORECASE,
    )

    seen: set[str] = set()
    chunk_ids: list[str] = []

    for chunk_id in matches:
        chunk_id = str(chunk_id)

        if chunk_id not in seen:
            seen.add(chunk_id)
            chunk_ids.append(chunk_id)

    return chunk_ids


def get_retrieved_chunk_ids(
    documents: list[dict[str, Any]],
) -> set[str]:
    """
    Return all chunk IDs from retrieved documents.
    """

    return {
        str(document["chunk_id"])
        for document in documents
        if document.get("chunk_id") is not None
    }


def get_metadata(
    document: dict[str, Any],
) -> dict[str, Any]:
    """
    Return normalized metadata.
    """

    metadata = document.get("metadata")

    if not isinstance(metadata, dict):
        return {}

    return metadata


# ============================================================
# 1. Generated sources must match retrieved chunks
# ============================================================


@pytest.mark.asyncio
async def test_generated_sources_match_retrieved_chunks(
    rag_services,
):
    """
    Verify that every explicit citation generated by the
    model refers to a chunk that was actually retrieved.

    Example:

        Retrieved:
            chunk-123
            chunk-456

        Valid:
            According to [chunk-123] ...

        Invalid:
            According to [chunk-999] ...

    The current RAG pipeline does not explicitly require
    citations, so an answer without citation markers is
    accepted here.
    """

    query = "How does audio enhancement work?"

    # --------------------------------------------------------
    # Retrieve source documents
    # --------------------------------------------------------

    documents = await rag_retriever.retrieve(
        query
    )

    # --------------------------------------------------------
    # Generate answer using the SAME helper used by the
    # existing hallucination evaluation.
    # --------------------------------------------------------

    answer = await run_pipeline(
        query
    )

    retrieved_ids = get_retrieved_chunk_ids(
        documents
    )

    cited_ids = extract_chunk_ids_from_answer(
        answer
    )

    invalid_citations = [
        chunk_id
        for chunk_id in cited_ids
        if chunk_id not in retrieved_ids
    ]

    print()
    print("=" * 70)
    print("SOURCE / CITATION ACCURACY")
    print("=" * 70)

    print(
        f"Query: {query}"
    )

    print(
        f"Retrieved chunks: "
        f"{sorted(retrieved_ids)}"
    )

    print(
        f"Generated citations: "
        f"{cited_ids}"
    )

    print(
        f"Invalid citations: "
        f"{invalid_citations}"
    )

    print(
        f"Answer: {answer}"
    )

    assert not invalid_citations, (
        "Generated answer contains citations "
        "for chunks that were not retrieved: "
        f"{invalid_citations}"
    )


# ============================================================
# 2. Source metadata correctness
# ============================================================


@pytest.mark.asyncio
async def test_retrieved_source_metadata_is_correct(
    rag_services,
):
    """
    Verify that every retrieved document has a valid source
    structure.

    Expected normalized document:

        {
            "chunk_id": "...",
            "text": "...",
            "score": ...,
            "metadata": {...}
        }

    This validates the source metadata returned by the
    retriever without changing the retriever implementation.
    """

    query = "How does audio enhancement work?"

    documents = await rag_retriever.retrieve(
        query
    )

    print()
    print("=" * 70)
    print("SOURCE METADATA ACCURACY")
    print("=" * 70)

    print(
        f"Query: {query}"
    )

    assert documents, (
        "Expected at least one retrieved document."
    )

    seen_chunk_ids: set[str] = set()

    for document in documents:

        chunk_id = document.get(
            "chunk_id"
        )

        text = document.get(
            "text"
        )

        score = document.get(
            "score"
        )

        metadata = get_metadata(
            document
        )

        print()
        print(
            f"Chunk ID: {chunk_id}"
        )

        print(
            f"Score: {score}"
        )

        print(
            f"Metadata: {metadata}"
        )

        # ----------------------------------------------------
        # chunk_id
        # ----------------------------------------------------

        assert chunk_id is not None, (
            "Retrieved source is missing chunk_id."
        )

        chunk_id = str(chunk_id)

        assert chunk_id.strip(), (
            "Retrieved source has an empty chunk_id."
        )

        # ----------------------------------------------------
        # No duplicate chunk IDs
        # ----------------------------------------------------

        assert chunk_id not in seen_chunk_ids, (
            f"Duplicate chunk ID returned by retriever: "
            f"{chunk_id}"
        )

        seen_chunk_ids.add(
            chunk_id
        )

        # ----------------------------------------------------
        # Text
        # ----------------------------------------------------

        assert isinstance(
            text,
            str,
        ), (
            f"Source {chunk_id} has invalid text type."
        )

        assert text.strip(), (
            f"Source {chunk_id} contains empty text."
        )

        # ----------------------------------------------------
        # Score
        # ----------------------------------------------------

        assert isinstance(
            score,
            (int, float),
        ), (
            f"Source {chunk_id} has invalid score."
        )

        assert 0.0 <= float(score) <= 1.0, (
            f"Source {chunk_id} has invalid relevance "
            f"score: {score}"
        )

        # ----------------------------------------------------
        # Metadata
        # ----------------------------------------------------

        assert isinstance(
            metadata,
            dict,
        ), (
            f"Source {chunk_id} metadata must be a dict."
        )


# ============================================================
# 3. Citation -> correct retrieved document
# ============================================================


@pytest.mark.asyncio
async def test_citations_point_to_correct_document(
    rag_services,
):
    """
    Verify that citations in the generated answer point to
    retrieved documents.

    If the current model does not produce explicit citations,
    the test is skipped because there is no citation contract
    to validate yet.
    """

    query = "What audio formats are supported?"

    documents = await rag_retriever.retrieve(
        query
    )

    answer = await run_pipeline(
        query
    )

    documents_by_id = {
        str(document["chunk_id"]): document
        for document in documents
        if document.get("chunk_id") is not None
    }

    cited_ids = extract_chunk_ids_from_answer(
        answer
    )

    print()
    print("=" * 70)
    print("CITATION -> DOCUMENT ACCURACY")
    print("=" * 70)

    print(
        f"Query: {query}"
    )

    print(
        f"Retrieved chunks: "
        f"{list(documents_by_id.keys())}"
    )

    print(
        f"Cited chunks: "
        f"{cited_ids}"
    )

    print(
        f"Answer: {answer}"
    )

    # --------------------------------------------------------
    # Current pipeline does not explicitly generate citations.
    # --------------------------------------------------------

    if not cited_ids:
        pytest.skip(
            "No explicit chunk citations were generated "
            "by the current RAG pipeline."
        )

    # --------------------------------------------------------
    # Every citation must map to a retrieved document.
    # --------------------------------------------------------

    for cited_id in cited_ids:

        assert cited_id in documents_by_id, (
            f"Citation [{cited_id}] does not correspond "
            "to any retrieved document."
        )

        document = documents_by_id[
            cited_id
        ]

        assert str(
            document["chunk_id"]
        ) == cited_id, (
            f"Citation [{cited_id}] points to the wrong "
            "document."
        )

        assert document.get(
            "text"
        ), (
            f"Cited document [{cited_id}] has no source text."
        )


# ============================================================
# 4. No fabricated source IDs
# ============================================================


@pytest.mark.asyncio
async def test_no_fabricated_source_ids(
    rag_services,
):
    """
    Verify that the model does not cite a source that was
    not retrieved.

    This is a direct hallucinated-source test.
    """

    query = "What audio formats are supported?"

    documents = await rag_retriever.retrieve(
        query
    )

    answer = await run_pipeline(
        query
    )

    retrieved_ids = get_retrieved_chunk_ids(
        documents
    )

    cited_ids = extract_chunk_ids_from_answer(
        answer
    )

    fabricated_ids = [
        cited_id
        for cited_id in cited_ids
        if cited_id not in retrieved_ids
    ]

    print()
    print("=" * 70)
    print("FABRICATED SOURCE CHECK")
    print("=" * 70)

    print(
        f"Retrieved IDs: "
        f"{sorted(retrieved_ids)}"
    )

    print(
        f"Cited IDs: "
        f"{cited_ids}"
    )

    print(
        f"Fabricated IDs: "
        f"{fabricated_ids}"
    )

    print(
        f"Answer: {answer}"
    )

    assert not fabricated_ids, (
        "Model generated fabricated source IDs: "
        f"{fabricated_ids}"
    )